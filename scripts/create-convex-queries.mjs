#!/usr/bin/env node
// Generates apps/fullstack/convex/queries.ts from apps/fullstack/state-model.json:
// one read ("list") query per entity, so the cockpit's live consumer can read
// the same shapes it renders from the static bundle today (the consumer_contract).
// Run with --check to verify the committed queries match the model.
//
// Deferred source: compiles after `npx convex dev` codegen at provisioning
// (which creates ./_generated/server). No dependency is added now — the
// generator is pure Node. Auth is applied at provisioning via Convex Auth
// (owner-only reads per docs/decisions/auth-jwt-decision-record.md).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modelPath = resolve(root, "apps/fullstack/state-model.json");
const outPath = resolve(root, "apps/fullstack/convex/queries.ts");

const model = JSON.parse(readFileSync(modelPath, "utf8"));

const pascalCase = (snake) =>
  snake
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const queries = Object.entries(model.entities)
  .map(([name, entity]) => {
    return [
      `// ${entity.description}`,
      `export const list${pascalCase(name)} = query({`,
      `  args: {},`,
      `  handler: async (ctx) => await ctx.db.query("${name}").collect(),`,
      `});`,
    ].join("\n");
  })
  .join("\n\n");

const banner =
  "// Generated by scripts/create-convex-queries.mjs from apps/fullstack/state-model.json.\n" +
  "// Do not edit by hand. Regenerate with: npm run automation:convex-queries\n" +
  "//\n" +
  "// Deferred source: compiles after `npx convex dev` codegen at backend\n" +
  "// provisioning. Reads are owner-only via Convex Auth once provisioned\n" +
  "// (docs/decisions/auth-jwt-decision-record.md).\n";

const output = `${banner}import { query } from "./_generated/server";

${queries}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    current = "";
  }
  if (current !== output) {
    console.error("convex-queries check failed: queries out of date. Run npm run automation:convex-queries");
    process.exit(1);
  }
  console.log(`convex-queries check passed (${Object.keys(model.entities).length} queries).`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, output);
  console.log(`Wrote ${outPath} (${Object.keys(model.entities).length} queries).`);
}
