#!/usr/bin/env node
// Generates apps/fullstack/convex/schema.ts from the committed state model in
// apps/fullstack/state-model.json so the live Convex backend uses the same
// entity shapes the static cockpit already renders (the consumer_contract).
// Run with --check to verify the committed schema matches the model.
//
// This is deferred source: it compiles once `convex` is installed at backend
// provisioning. No dependency is added now — the generator is pure Node.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modelPath = resolve(root, "apps/fullstack/state-model.json");
const outPath = resolve(root, "apps/fullstack/convex/schema.ts");

const model = JSON.parse(readFileSync(modelPath, "utf8"));

// Map a state-model field description to a Convex validator. The leading token
// before " — " carries the type; the rest is human documentation.
const validatorFor = (description) => {
  const token = String(description).split("—")[0].trim().toLowerCase();
  switch (token) {
    case "boolean":
      return "v.boolean()";
    case "number":
      return "v.number()";
    case "string|null":
      return "v.union(v.string(), v.null())";
    case "string":
    default:
      return "v.string()";
  }
};

const indent = (n) => "  ".repeat(n);

const tables = Object.entries(model.entities)
  .map(([name, entity]) => {
    const fields = Object.entries(entity.fields)
      .map(([field, description]) => `${indent(2)}${field}: ${validatorFor(description)},`)
      .join("\n");
    return [
      `${indent(1)}// ${entity.description}`,
      `${indent(1)}${name}: defineTable({`,
      fields,
      `${indent(1)}}),`,
    ].join("\n");
  })
  .join("\n\n");

const banner =
  "// Generated by scripts/create-convex-schema.mjs from apps/fullstack/state-model.json.\n" +
  "// Do not edit by hand. Regenerate with: npm run automation:convex-schema\n" +
  "//\n" +
  "// Deferred source: requires `convex` (installed at backend provisioning per\n" +
  "// docs/decisions/backend-state-decision-record.md). The static cockpit keeps\n" +
  "// working unchanged until the live backend is provisioned.\n";

const output = `${banner}import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
${tables}
});
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    current = "";
  }
  if (current !== output) {
    console.error("convex-schema check failed: schema out of date. Run npm run automation:convex-schema");
    process.exit(1);
  }
  console.log(`convex-schema check passed (${Object.keys(model.entities).length} tables).`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, output);
  console.log(`Wrote ${outPath} (${Object.keys(model.entities).length} tables).`);
}
